/* Generated catalog is checked in: GitHub Pages needs no build server. */
'use strict';
const fs = require('node:fs'), path = require('node:path');
const catalogs = Object.fromEntries(['en','ru'].map(lang => [lang, JSON.parse(fs.readFileSync(path.join(__dirname, lang+'.json'),'utf8'))]));
const output = '/* Generated by node assets/i18n/build-catalogs.cjs. Edit en.json / ru.json. */\nwindow.AXIOM_I18N_CATALOGS='+JSON.stringify(catalogs)+';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(__dirname,'catalogs.js'),'utf8') !== output) { console.error('Stale i18n catalog: run node assets/i18n/build-catalogs.cjs'); process.exit(1); }
} else fs.writeFileSync(path.join(__dirname,'catalogs.js'),output);
