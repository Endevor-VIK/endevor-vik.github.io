#!/usr/bin/env python3
"""0524.W4.R R2 — integrate the CREATOR-approved A+AD (art freeze 9cf78b0) into the product, stage by stage.

Deterministic: product(stage N) = b85fbb0a index.html with the sections of stages <= N taken verbatim from the frozen
A+AD prototype, plus one scoped stylesheet and one deferred script. All inputs are read from Git objects, never from
the working tree, so the freeze cannot drift. Every edit asserts a single hit; protected internals are compared with
b85fbb0a; at the final stage the product must equal the prototype up to the recorded path mapping.

Usage: python3 docs/showcase-v031/evidence/w4r2/tools/build_r2.py --stage {1,2,3}
Writes: index.html, assets/css/showcase-w4r.css, assets/js/showcase-w4r.js,
        assets/showcase/visual-library/web/A08_protocol_gate-{480,720,941}w.{avif,webp}
"""
import argparse, hashlib, json, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
PRODUCT = 'b85fbb0a1cb4f4370dd35347b5b6dc57fac1f0b5'
FREEZE = '9cf78b0'
AD = 'docs/showcase-v031/evidence/w4ad/preview/'
R1P = 'docs/showcase-v031/evidence/w4rp/preview/r1p.css'
CSS_OUT, JS_OUT = 'assets/css/showcase-w4r.css', 'assets/js/showcase-w4r.js'
A08_DIR = 'assets/showcase/visual-library/web/'
STAGE_SECTIONS = {1: ('manifesto', 'modules'), 2: ('work',), 3: ('world', 'chars')}
# Recorded deviations from the frozen prototype (waves/w4ad/OPUS_DECISIONS.md). Nothing else may differ.
CSS_DEVIATIONS = [('#ffd5da', 'var(--ax-ink)', 'D-01: standing CREATOR palette rule (no pink); pulse glint becomes neutral ink')]


def git(ref_path, binary=False):
    out = subprocess.check_output(['git', 'show', ref_path], cwd=ROOT)
    return out if binary else out.decode()


def block(s, pattern):
    m = re.search(pattern, s)
    assert m, pattern
    tag = re.match(r'<([\w:-]+)', m.group()).group(1); depth = 0
    for t in re.finditer(r'<!--[\s\S]*?-->|</?([\w:-]+)\b[^>]*>', s[m.start():]):
        v = t.group()
        if v.startswith('<!--') or t.group(1) != tag: continue
        if v.startswith('</'): depth -= 1
        elif not v.endswith('/>'): depth += 1
        if depth == 0: return s[m.start():m.start() + t.end()]
    raise ValueError(pattern)


def section(s, sid):
    return block(s, rf'<section\b[^>]*\bid="{sid}"[^>]*>')


def sub1(s, old, new, why):
    assert s.count(old) == 1, (why, s.count(old))
    return s.replace(old, new, 1)


# ------------------------------------------------------------------ CSS: ordered rule list, filtered by stage
def parse_css(text):
    text = re.sub(r'/\*[\s\S]*?\*/', '', text)
    rules, i, media = [], 0, None
    while i < len(text):
        if text[i].isspace(): i += 1; continue
        if text[i] == '}':
            assert media is not None, 'unbalanced }'
            media = None; i += 1; continue
        j = text.index('{', i); prelude = text[i:j].strip()
        if prelude.startswith('@media'):
            assert media is None, 'nested @media'
            media = prelude; i = j + 1; continue
        if prelude.startswith('@keyframes'):
            depth, k = 0, j
            while True:
                depth += {'{': 1, '}': -1}.get(text[k], 0); k += 1
                if depth == 0: break
            rules.append((media, prelude, text[j + 1:k - 1].strip())); i = k; continue
        k = text.index('}', j)
        rules.append((media, prelude, text[j + 1:k].strip())); i = k + 1
    assert media is None
    return rules


R22 = ('.r1p-surfaces', '.r1p-exhibit', '.ad-surface-index')
R23 = ('.r1p-plate-copy', '.r1p-map-intro', '.r1p-character-intro')


def rule_stage(selector):
    stages = []
    for part in selector.split(','):
        stages.append(2 if any(k in part for k in R22) else 3 if any(k in part for k in R23) else 1)
    return min(stages)  # a selector list ships with its earliest stage; later-stage parts stay inert until their markup


def emit(rules):
    out, media = [], None
    for m, sel, body in rules:
        if m != media:
            if media: out.append('}')
            if m: out.append(m + '{')
            media = m
        out.append((' ' if m else '') + f'{sel}{{{body}}}')
    if media: out.append('}')
    return '\n'.join(out) + '\n'


def build_css(stage):
    src_r1p, src_ad = git(f'{FREEZE}:{R1P}'), git(f'{FREEZE}:{AD}ad.css')
    for old, new, _ in CSS_DEVIATIONS:
        assert src_ad.count(old) == 2, old
        src_ad = src_ad.replace(old, new)
    rules = parse_css(src_r1p) + parse_css(src_ad)
    kept = [r for r in rules if rule_stage(r[1]) <= stage]
    head = ('/* 0524.W4.R R2 — approved A+AD (art freeze 9cf78b0): BLACK SUN / WHAT REMAINS'
            + (', WORK surface studies' if stage >= 2 else '') + (', WORLD / CHARACTERS introductions' if stage >= 3 else '') + '.\n'
            '   Generated by docs/showcase-v031/evidence/w4r2/tools/build_r2.py from the frozen r1p.css + ad.css, rule order\n'
            '   preserved; scoped to the new markup only. Deviation D-01: pulse glint uses --ax-ink instead of pale pink. */\n')
    css = head + emit(kept)
    assert parse_css(css) == kept, 'emitted CSS does not round-trip'
    return css, len(kept), len(rules)


# ------------------------------------------------------------------ build
def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--stage', type=int, choices=(1, 2, 3), required=True)
    stage = ap.parse_args().stage
    base, ad = git(f'{PRODUCT}:index.html'), git(f'{FREEZE}:{AD}ad.html')
    out, log = base, []
    for n in range(1, stage + 1):
        for sid in STAGE_SECTIONS[n]:
            new = section(ad, sid).replace('src="proposed/A08_protocol_gate-', f'src="{A08_DIR}A08_protocol_gate-')
            new = re.sub(r'(?<=[" ,])proposed/A08_protocol_gate-', A08_DIR + 'A08_protocol_gate-', new)
            assert 'proposed/' not in new
            out = sub1(out, section(out, sid), new, f'R2.{n}: #{sid} from A+AD')
            log.append(f'R2.{n}: #{sid} replaced verbatim from {FREEZE} (A08 paths mapped to {A08_DIR})')
    out = sub1(out, '</head>', f'<link rel="stylesheet" href="{CSS_OUT}">\n</head>', 'head: scoped stylesheet last, as in prototype')
    out = sub1(out, '<script src="assets/js/showcase-v23.js" defer></script>',
               f'<script src="assets/js/showcase-v23.js" defer></script>\n<script src="{JS_OUT}" defer></script>', 'body: rail script after v23')

    # Protected: everything outside the stage sections is byte-identical to the product baseline.
    changed = {sid for n in range(1, stage + 1) for sid in STAGE_SECTIONS[n]}
    ids = re.findall(r'<section\b[^>]*\bid="([^"]+)"', base)
    assert ids == re.findall(r'<section\b[^>]*\bid="([^"]+)"', out), 'section order changed'
    for sid in ids:
        if sid not in changed:
            assert section(base, sid) == section(out, sid), f'unexpected change in #{sid}'
    for name, pattern in [('map', r'<div class="v23-map-composition">'), ('axes', r'<div class="v23-map-axes"[^>]*>'), ('omega', r'<div class="ax-omega">'),
                          ('cards', r'<div class="chars">'), ('axiom', r'<div class="axiom-entity"[^>]*>'), ('viewer', r'<dialog[^>]*id="showcase-lightbox"[^>]*>')]:
        assert block(base, pattern) == block(out, pattern), name
    w04 = lambda s: block(section(s, 'world'), r'<picture>')
    assert w04(base) == w04(out), 'W04 picture'
    shots = lambda s: re.findall(r'<figure class="ax-shot">[\s\S]*?</figure>', s)
    assert len(shots(base)) == 8 and shots(base) == shots(out), 'eight real screenshots'

    if stage == 3:  # the product is the approved prototype, up to the recorded mapping
        expect = ad.replace('<link rel="stylesheet" href="r1p.css">\n<link rel="stylesheet" href="ad.css">\n</head>', f'<link rel="stylesheet" href="{CSS_OUT}">\n</head>')
        expect = expect.replace('<script src="ad.js" defer></script>', f'<script src="{JS_OUT}" defer></script>').replace('proposed/A08_protocol_gate-', A08_DIR + 'A08_protocol_gate-')
        assert out == expect, 'final product differs from A+AD beyond the recorded mapping'
        log.append('R2.3: index.html == A+AD prototype modulo stylesheet/script/A08 paths')

    css, kept, total = build_css(stage)
    js = git(f'{FREEZE}:{AD}ad.js').replace('/* W4.AD prototype only: progressive controls for snap rails.',
                                            '/* 0524.W4.R R2 (A+AD, art freeze 9cf78b0): progressive controls for snap rails.')
    assert js.startswith('/* 0524.W4.R R2')
    deriv = json.loads(git(f'{FREEZE}:{AD}proposed-assets/derivatives.json'))
    (ROOT / A08_DIR).mkdir(parents=True, exist_ok=True)
    for item in deriv['web']:
        data = git(f'{FREEZE}:{AD}proposed-assets/{item["file"]}', binary=True)
        assert hashlib.sha256(data).hexdigest() == item['sha256'], item['file']
        (ROOT / A08_DIR / item['file']).write_bytes(data)
    (ROOT / 'index.html').write_text(out)
    (ROOT / CSS_OUT).write_text(css)
    (ROOT / JS_OUT).write_text(js)
    sha = lambda b: hashlib.sha256(b.encode() if isinstance(b, str) else b).hexdigest()
    print(json.dumps({'stage': f'R2.{stage}', 'freeze': FREEZE, 'product_base': PRODUCT, 'edits': log,
                      'css_rules': f'{kept}/{total}', 'deviations': [d[2] for d in CSS_DEVIATIONS],
                      'sha256': {'index.html': sha(out), CSS_OUT: sha(css), JS_OUT: sha(js)}}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
